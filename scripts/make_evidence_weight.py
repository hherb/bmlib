"""Write ``tests/fixtures/evidence_weight.json`` from the Python pipeline.

The shared contract of the unattended pipeline that Python and Rust both
assert against.  Each case is the model's replies in the order the pipeline
asks for them and the ``EvidenceWeight`` it returns (one of each status, the
assessed one with a ladder, a refused result and a failed domain, so every
kind of ``ladder_error`` appears); each refusal is a change to the assessed
case's wire form (see :func:`apply_change`) and the message reading it back
gives.

    python scripts/make_evidence_weight.py [tests/fixtures/evidence_weight.json]

``tests/test_evidence_weight_contract.py`` checks that this script still
builds the committed fixture, so add a case here and re-run it.
"""

from __future__ import annotations

import copy
import json
import sys
from pathlib import Path
from typing import Any

from bmlib.llm.data_types import LLMResponse
from bmlib.quality.evidence_ladder import LadderSettings
from bmlib.quality.evidence_weight import assess_unattended, evidence_weight_from_dict
from bmlib.quality.rob2_d5_checks import D5_FACTS

DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "tests/fixtures/evidence_weight.json"

DESIGN_QUOTE = "Participants were randomly assigned 1:1 to metformin or placebo."
OUTCOME_QUOTE = "The primary outcome was all-cause mortality at 28 days."
RANDOM = "The allocation sequence was generated by computer."
TITLE = "A trial of metformin"
ANALYSIS_QUOTE = "Mortality was analysed with the prespecified log-binomial regression."
TEXT = (
    f"{DESIGN_QUOTE} {OUTCOME_QUOTE} {RANDOM} Allocation was concealed centrally. {ANALYSIS_QUOTE}"
)
MIN_SIMILARITY = 0.9


def _design(study_design: str, layout: str | None) -> dict[str, Any]:
    return {
        "study_design": study_design,
        "rct_layout": layout,
        "quotes": [DESIGN_QUOTE],
        "reasoning": "As the methods say.",
    }


def _outcome(name: str, **result: Any) -> dict[str, Any]:
    body = {
        "measure": "risk ratio",
        "scale": "ratio",
        "estimate": 0.7,
        "ci_low": 0.55,
        "ci_high": 0.88,
        "ci_level": 95,
        "n_analysed": 1200,
    }
    body.update(result)
    return {"name": name, "timepoint": "28 days", "quotes": [OUTCOME_QUOTE], "result": body}


def _answers(**answers: str) -> dict[str, Any]:
    """A domain reply; ``q1_1="Y"`` answers ``"1.1"``."""
    return {
        "answers": {
            key[1:].replace("_", "."): {"answer": a, "quotes": [], "reasoning": "Why."}
            for key, a in answers.items()
        }
    }


D1 = _answers(q1_1="Y", q1_2="Y", q1_3="N")
D2 = _answers(q2_1="N", q2_2="N", q2_6="Y")
D3 = _answers(q3_1="Y")
D4 = _answers(q4_1="N", q4_2="N", q4_3="N")
#: D5 from facts (design §4.6): the paper states mortality's measure, time point and analysis as
#: set in advance, so its D5 is low on the paper's word; the other outcomes, which no quote
#: names, are some concerns.
D5 = {
    "facts": {f.value: {"present": False, "quotes": []} for f in D5_FACTS}
    | {
        "measure_fixed": {"present": True, "quotes": [OUTCOME_QUOTE]},
        "timepoint_fixed": {"present": True, "quotes": [OUTCOME_QUOTE]},
        "analysis_fixed": {"present": True, "quotes": [ANALYSIS_QUOTE]},
    },
    "other_measurements": [],
    "main_analysis": {"differs": False, "planned": [], "reported": []},
}
UNREADABLE_D3 = _answers(q3_1="Unclear")

# (name, replies in the order the pipeline asks for them)
CASES: list[tuple[str, list[Any]]] = [
    ("not covered", [_design("cohort_prospective", None)]),
    ("a crossover trial is not covered", [_design("rct", "crossover")]),
    ("no primary outcome", [_design("rct", "parallel"), {"primary_outcomes": []}]),
    (
        "assessed, with a ladder, a refused result and a failed domain",
        [
            _design("rct", "parallel"),
            {
                "primary_outcomes": [
                    _outcome("All-cause mortality"),
                    _outcome("Hospital admission", ci_low="NR"),
                    _outcome(
                        "Length of stay",
                        scale="difference",
                        estimate=-1.5,
                        ci_low=-3.0,
                        ci_high=0.2,
                        n_analysed=180,
                    ),
                    _outcome("Readmission"),
                ]
            },
            D1,
            *(D2, D3, D4, D5),
            *(D2, D3, D4, D5),
            *(D2, D3, D4, D5),
            *(D2, UNREADABLE_D3, UNREADABLE_D3, D4, D5),
        ],
    ),
]


class _Scripted:
    """An ``LLMClient`` stand-in that answers each request with the next reply."""

    default_provider = "test"

    def __init__(self, replies: list[Any]) -> None:
        self._replies = iter(replies)

    def _get_provider(self, name: str) -> None:
        """Every provider exists here."""

    def chat(self, **_kwargs: Any) -> LLMResponse:
        """The next reply, as the provider would return it."""
        return LLMResponse(json.dumps(next(self._replies)), "test:model", 1, 1, "stop")


def _run(replies: list[Any]) -> dict[str, Any]:
    result = assess_unattended(
        _Scripted(replies),  # type: ignore[arg-type]
        "test:model",
        settings=LadderSettings(),
        title=TITLE,
        text=TEXT,
        min_similarity=MIN_SIMILARITY,
    )
    return result.to_dict()


def apply_change(wire: dict[str, Any], change: dict[str, Any]) -> None:
    """Apply one refusal's change to *wire* in place.

    ``path`` leads to the value changed; ``"set"`` replaces it, ``"remove"``
    deletes it (the last member of a list when the path ends at the list) and
    ``"reverse"`` reverses the list there.
    """
    *parents, last = change["path"]
    target: Any = wire
    for key in parents:
        target = target[key]
    if "set" in change:
        target[last] = change["set"]
    elif change.get("remove"):
        if isinstance(target[last], list):
            target[last].pop()
        else:
            del target[last]
    else:
        target[last].reverse()


# (name, change to the assessed case's wire form); each is refused.
REFUSALS: list[tuple[str, dict[str, Any]]] = [
    ("status unknown", {"path": ["status"], "set": "maybe"}),
    ("another ladder version", {"path": ["ladder_version"], "set": "ladder/0"}),
    ("ladder version not text", {"path": ["ladder_version"], "set": 1}),
    ("settings refused", {"path": ["settings", "high_steps"], "set": -1}),
    ("settings with an unknown field", {"path": ["settings", "extra"], "set": 1}),
    ("settings missing", {"path": ["settings"], "remove": True}),
    ("design prompt version negative", {"path": ["design", "prompt_version"], "set": -1}),
    ("outcome prompt version missing", {"path": ["outcomes", "prompt_version"], "remove": True}),
    ("an assessed outcome missing", {"path": ["assessed"], "remove": True}),
    ("assessed out of order", {"path": ["assessed"], "reverse": True}),
    ("ladder and ladder error both set", {"path": ["assessed", 0, "ladder_error"], "set": "x"}),
]


def build_contract() -> dict[str, Any]:
    """Build the whole contract from the Python implementation."""
    cases = [{"name": n, "replies": r, "expected": _run(r)} for n, r in CASES]
    assessed = cases[-1]["expected"]
    refusals = []
    for name, change in REFUSALS:
        wire = copy.deepcopy(assessed)
        apply_change(wire, change)
        try:
            evidence_weight_from_dict(wire)
        except ValueError as exc:
            refusals.append({"name": name, "change": change, "error": str(exc)})
        else:
            raise AssertionError(f"{name} was accepted")
    return {
        "title": TITLE,
        "text": TEXT,
        "min_similarity": MIN_SIMILARITY,
        "cases": cases,
        "refusals": refusals,
    }


def main() -> None:
    """Write the contract to the path given, or to the committed fixture."""
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUTPUT
    text = json.dumps(build_contract(), ensure_ascii=False, indent=1) + "\n"
    output.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
