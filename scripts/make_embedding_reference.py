def main() -> None:
    print(
        f"sentence-transformers {sentence_transformers.__version__}, torch {torch.__version__}",
        file=sys.stderr,
    )
    model = SentenceTransformer(BASE_MODEL, revision=BASE_REVISION, device="cpu")
    out = []
    for name, kind, text in ITEMS:
        kwargs = {"prompt_name": "query"} if kind == "query" else {}
        full = model.encode(text, convert_to_numpy=True, show_progress_bar=False, **kwargs)
        vec = np.asarray(full[:DIM], dtype=np.float64)
        vec /= np.linalg.norm(vec)
        out.append(
            {"name": name, "kind": kind, "text": text, "vector": [float(f"{x:.7g}") for x in vec]}
        )
        print(name, file=sys.stderr)
    json.dump(
        {
            "_readme": README,
            "base_model": BASE_MODEL,
            "base_revision": BASE_REVISION,
            "dim": DIM,
            "items": out,
        },
        sys.stdout,
        ensure_ascii=False,
        indent=1,
    )
    print()


if __name__ == "__main__":
    main()
