//! Citations — the named tests.
//!
//! [`citations_oracle`] is the broad instrument: 93 cases generated by running
//! the Python library, diffed semantically. This file is the *reasoned* half —
//! tests that say what a behaviour is for, and the regression tests for the
//! defect the port fixes.
//!
//! Anything already covered by the oracle is deliberately **not** repeated
//! here. What is here is: the defect fix, the upstream-faithful oddities that
//! look like bugs, and the properties a reader needs stated.

use bmlib::citations::models::{author_surname, CitationStyle, DocumentMetadata};
use bmlib::citations::{CitationFormatter, MAX_AUTHORS_BEFORE_ET_AL};

fn metadata(authors: &[&str], year: Option<i64>) -> DocumentMetadata {
    let mut m = DocumentMetadata::new(1, "T");
    m.authors = authors.iter().map(|a| (*a).to_string()).collect();
    m.year = year;
    m
}

// ---------------------------------------------------------------------------
// The defect this port fixes rather than reproduces — issue #296
// ---------------------------------------------------------------------------

/// Python's inline formatters branch on `len(metadata.authors)` — the raw
/// list — while the reference formatters filter whitespace-only entries
/// first. So a blank author made the two disagree:
///
/// ```text
/// authors = ["John Smith", "Anna Johnson", "   "]
///   reference: "Smith, J. & Johnson, A. (2023) T."      <- 2 named
///   inline:    "(Smith et al., 2023)"                   <- counted 3
/// ```
///
/// The port counts named authors everywhere, so the two cannot disagree.
#[test]
fn a_trailing_blank_author_does_not_make_two_authors_read_as_three() {
    let m = metadata(&["John Smith", "Anna Johnson", "   "], Some(2023));
    let f = CitationFormatter::new(CitationStyle::Apa);
    assert_eq!(
        f.format_reference(&m, None),
        "Smith, J. & Johnson, A. (2023) T."
    );
    // Python said "(Smith et al., 2023)" here.
    assert_eq!(
        f.format_inline_citation(&m, None),
        "(Smith & Johnson, 2023)"
    );
}

/// The other direction, and the false attribution: Python's
/// `get_first_author_surname()` read `authors[0]` unfiltered, so a blank first
/// author rendered `(Unknown & Johnson, 2023)` and a label `Unknown2023` —
/// even though the reference named Johnson.
#[test]
fn a_blank_first_author_is_not_attributed_to_unknown() {
    let m = metadata(&["   ", "Anna Johnson"], Some(2023));
    let f = CitationFormatter::new(CitationStyle::Apa);
    assert_eq!(f.format_reference(&m, None), "Johnson, A. (2023) T.");
    // Python said "(Unknown & Johnson, 2023)".
    assert_eq!(f.format_inline_citation(&m, None), "(Johnson, 2023)");
    // Python said "Unknown2023", which `create_citation_marker` would then
    // write into a stored marker.
    assert_eq!(m.generate_label(), "Johnson2023");
}

/// A blank trailing author used to be counted as a second author, so a
/// one-author paper rendered as an ampersand pair.
#[test]
fn a_trailing_blank_author_does_not_invent_a_second_author() {
    let m = metadata(&["John Smith", "   "], Some(2023));
    let f = CitationFormatter::new(CitationStyle::Apa);
    assert_eq!(f.format_reference(&m, None), "Smith, J. (2023) T.");
    // Python said "(Smith & Unknown, 2023)".
    assert_eq!(f.format_inline_citation(&m, None), "(Smith, 2023)");
}

/// An all-blank list is an author-less document, and every style already has
/// a branch for that. This is the case that keeps the fix from over-reaching.
#[test]
fn an_all_blank_author_list_reads_as_no_authors() {
    let m = metadata(&["   ", "\t"], Some(2023));
    assert_eq!(m.named_authors().len(), 0);
    assert_eq!(m.first_author_surname(), "Unknown");
    assert_eq!(m.generate_label(), "Unknown2023");
    for style in CitationStyle::all() {
        let f = CitationFormatter::new(style);
        assert!(
            f.format_reference(&m, Some(1)).contains("Unknown author"),
            "{style} should name no author"
        );
    }
}

/// The count is a property of the type, so no consumer can bypass it. This is
/// the structural half of the fix: Python had a private formatter helper that
/// three of four call paths forgot to use.
#[test]
fn every_author_consumer_sees_the_same_count() {
    let m = metadata(&["A One", "", "  ", "B Two"], Some(2020));
    assert_eq!(m.named_authors(), vec!["A One", "B Two"]);
    assert_eq!(m.author_count(), 2);
    for style in CitationStyle::all() {
        let inline = CitationFormatter::new(style).format_inline_citation(&m, None);
        assert!(
            !inline.contains("et al"),
            "{style} has two named authors, so no et al: {inline}"
        );
    }
}

