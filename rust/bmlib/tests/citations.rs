/// The register records this as one of five upstream-faithful oddities, pinned
/// by a Python test naming it. `"Firstname Surname"` is a naive split, so
/// particles are lost — only the inverted format keeps them.
#[test]
fn author_surname_is_a_naive_split_and_stays_one() {
    assert_eq!(author_surname("Jan van der Berg"), "Berg");
    assert_eq!(author_surname("van der Berg, Jan"), "van der Berg");
    assert_eq!(author_surname("Aristotle"), "Aristotle");
    assert_eq!(author_surname("   "), "Unknown");
}

/// `"Smithn.d."` — no separator, no space. Pinned by the register.
#[test]
fn a_label_without_a_year_is_smith_n_d() {
    assert_eq!(
        metadata(&["John Smith"], None).generate_label(),
        "Smithn.d."
    );
}

/// Harvard's natural branch keeps a middle initial's period; APA's inserts a
/// space; Vancouver drops the separator entirely. Three styles, three answers
/// for the same name — and only the differential oracle catches getting one of
/// them wrong, which is how this was found.
#[test]
fn the_three_initial_styles_differ_on_purpose() {
    let m = metadata(&["John A. Smith"], Some(2023));
    let harvard = CitationFormatter::new(CitationStyle::Harvard).format_reference(&m, None);
    let apa = CitationFormatter::new(CitationStyle::Apa).format_reference(&m, None);
    let vancouver = CitationFormatter::new(CitationStyle::Vancouver).format_reference(&m, None);
    assert!(harvard.starts_with("Smith, J.A."), "harvard: {harvard}");
    assert!(apa.starts_with("Smith, J. A."), "apa: {apa}");
    assert!(vancouver.contains("Smith JA"), "vancouver: {vancouver}");
}

/// APA elides the middle of a long list: six names, then `...`, then the
/// **last** name. Pinned by `test_eight_authors_elide_the_middle`.
#[test]
fn apa_elides_the_middle_of_a_long_author_list() {
    // Distinct surnames, so "which name was kept" is answerable. A generated
    // `Author{i} Given` list has one shared surname and cannot distinguish
    // them — which is what an earlier cut of this test got wrong.
    let mut m = DocumentMetadata::new(1, "T");
    m.authors = [
        "Alpha One",
        "Bravo Two",
        "Charlie Three",
        "Delta Four",
        "Echo Five",
        "Foxtrot Six",
        "Golf Seven",
        "Hotel Eight",
    ]
    .iter()
    .map(|s| (*s).to_string())
    .collect();
    let out = CitationFormatter::new(CitationStyle::Apa).format_reference(&m, None);
    assert!(out.contains(", ..., & "), "an ellipsis is expected: {out}");
    // APA inverts to "Surname, I.", so the surnames are the first words.
    let block = out.split(" (").next().expect("author block");
    assert_eq!(
        block.matches(", ..., & ").count(),
        1,
        "one ellipsis: {block}"
    );
    assert!(
        block.ends_with("Eight, H."),
        "the last author is kept: {block}"
    );
    assert!(!block.contains("Seven"), "the seventh is elided: {block}");
}

