/// Vancouver stops at the sixth name and appends a bare `et al`.
#[test]
fn vancouver_stops_at_the_sixth_name() {
    assert_eq!(MAX_AUTHORS_BEFORE_ET_AL, 6);
    let mut m = DocumentMetadata::new(1, "T");
    m.authors = [
        "Alpha One",
        "Bravo Two",
        "Charlie Three",
        "Delta Four",
        "Echo Five",
        "Foxtrot Six",
        "Golf Seven",
    ]
    .iter()
    .map(|s| (*s).to_string())
    .collect();
    let out = CitationFormatter::new(CitationStyle::Vancouver).format_reference(&m, Some(1));
    // Vancouver renders "Firstname Surname" as "Surname I", so the surnames are
    // the *second* word of each. Counting the author block's entries states the
    // rule without depending on that.
    let block = out
        .trim_start_matches("1. ")
        .split(". ")
        .next()
        .expect("author block");
    let names: Vec<&str> = block.split(", ").collect();
    assert_eq!(names.len(), 7, "six names plus et al: {block}");
    assert_eq!(names[6], "et al", "the sentinel is last: {block}");
    assert!(!block.contains("Seven"), "the seventh is dropped: {block}");
}

/// An empty title renders as `"Untitled"` — and **without** a period, because
/// the Python helper returns early rather than falling through to its
/// append-a-period branch. Pinned by the oracle too.
#[test]
fn an_empty_title_is_untitled_without_a_period() {
    let m = DocumentMetadata::new(1, "");
    let out = CitationFormatter::new(CitationStyle::Vancouver).format_reference(&m, Some(1));
    assert!(out.contains("Untitled"), "{out}");
    assert!(!out.contains("Untitled."), "no period is appended: {out}");
}

/// A marker carrying a `]` cannot parse, because the label runs to the first
/// `]`. The grammar is `[^\]]+`, so this is a documented limit rather than a
/// defect.
#[test]
fn a_label_containing_a_closing_bracket_ends_the_marker_early() {
    let parsed = bmlib::citations::parse_citations("[@id:1:a]b]");
    assert_eq!(parsed.len(), 1);
    assert_eq!(parsed[0].label, "a");
}

/// Positions are **character** offsets, matching Python's `match.start()` on a
/// `str`. A byte-offset implementation would disagree on any non-ASCII prefix.
#[test]
fn positions_are_character_offsets_not_byte_offsets() {
    let text = "Grüße 日本 [@id:1:A]";
    let parsed = bmlib::citations::parse_citations(text);
    assert_eq!(parsed.len(), 1);
    let expected = text.chars().position(|c| c == '[').unwrap();
    assert_eq!(parsed[0].position, expected);
}
